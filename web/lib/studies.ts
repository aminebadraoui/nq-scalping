export type Study = {
  id: string;
  title: string;
  date: string; // YYYY-MM-DD or "" for undated research
  question: string; // the one question the study answers
  category: StudyCategory;
  /** regenerating script under web/scripts/ ("" when research-only) */
  script: string;
  /** the exact regenerate commands (each entry = one shell line) */
  cli: string[];
  /** source doc under docs/research/ */
  doc: string;
  /** the script prints the standard report block (consolidated engine) */
  engine: boolean;
};

const cli = (script: string, extra: string[] = []): string[] =>
  ["cd web", `node --env-file=.env.local --import ../scripts/ts-loader.mjs ${script}`, ...extra];

